#creates a conformer list for a molecule
def conformer_list(molecule, extension='.xyz'):
    conformers=[]
    number_of_conformers = len([f for f in os.listdir() if f.endswith('.xyz') and f.startswith(str(molecule)) and os.path.isfile(os.path.join(f))])
    for conformer_number in range(1, number_of_conformers+1):
        conformers.append(str(molecule)+"_"+str(conformer_number) + str(extension))
    return conformers

#combines the a list of files.
def combine_files(list_of_filenames, combined_name):
    with open(str(combined_name), 'w') as outfile:
        for fname in list_of_filenames:
            with open(fname) as infile:
                outfile.write("{}\n".format(infile.read()))

#get the energy of the conformer generated by CREST (second line of xyz)
def get_energy(conformer):
    with open(conformer) as fp:
        for i, line in enumerate(fp):
            if i == 1:
                energy=line.split()[0]
    return energy

