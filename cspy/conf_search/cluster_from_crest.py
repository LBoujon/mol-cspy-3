#creates uniques.txt file which stores the conformer numbers of unique conformations from the clustering
def get_uniques():
    uniques_list=[]
    with open('clusters_careful_'+ str(single_angle) + '_' + str(rms_angle) + '.txt', 'r') as clusters:
        for line in clusters:
            uniques_list.append(line.split()[0])
    uniques_list_fn=[str(ident)+'_'+str(n)+'.xyz' for n in uniques_list]
    combine_files(uniques_list_fn, 'uniques.xyz')
    with open('uniques.txt', 'a') as uniques:
        for unique in uniques_list:
            uniques.write("{}\n".format(unique))
    print("{} total unique conformers found.".format(len(uniques_list)))

